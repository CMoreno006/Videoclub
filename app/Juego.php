<?php
namespace Dwes\ProyectoVideoclub;
class Juego extends Soporte{

    public string $consola;
    private int $minNumJugadores;
    private int $maxNumJugadores;

    public function __construct(string $titulo, int $numero, float $precio, string $consola, int $minNumJugadores, int $maxNumJugadores)
    {
        parent::__construct($titulo, $numero, $precio);
        $this->consola = $consola;
        $this->minNumJugadores = $minNumJugadores;
        $this->maxNumJugadores = $maxNumJugadores;
    }

    public function muestraJugadoresPosibles()
    {
        if($this->minNumJugadores==$this->maxNumJugadores){
            if($this->minNumJugadores==1)
            {
                echo "Para un jugador";
            }
            else
            {
                echo "Para ".$this->minNumJugadores." jugador/es";
            }
        }
        else
        {
            echo "De ".$this->minNumJugadores." jugadores/es a ".$this->maxNumJugadores;
        }
    }

    public function getPrecio(): float
    {
        return parent::getPrecio(); // TODO: Change the autogenerated stub
    }

    public function getNumero(): int
    {
        return parent::getNumero(); // TODO: Change the autogenerated stub
    }

    public function getPrecioConIva(): float
    {
        return parent::getPrecioConIva(); // TODO: Change the autogenerated stub
    }

    public function muestraResumen(): void
    {
        parent::muestraResumen(); // TODO: Change the autogenerated stub
        echo "<br>Consola: " . $this->consola . "";
        echo "<br>Min jugadores: ".$this->minNumJugadores;
        echo "<br>Max jugadores: ".$this->maxNumJugadores;
        echo "<br>".$this->muestraJugadoresPosibles();
    }

}